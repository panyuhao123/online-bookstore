-- =====================================================================
-- V7：书单治理状态列
--
-- 背景：V6 建 book_list 时只考虑了「用户自己的公开/私密」（is_public），
-- 那不是治理语义 —— 用户把书单设成公开，不代表平台认可其内容。
-- 管理端要处理违规书单（搬运广告、导流外链、违规书名），必须有一个
-- 与 is_public 正交的「平台可见性」维度。
--
-- 设计要点：
--   1) 新增 status 而不是复用 is_public：二者语义不同且必须能独立取值 ——
--      「用户设了公开」+「平台已隐藏」是合法组合（隐藏只作用于平台展示，
--      不替用户改他自己的设置，恢复时才能原样还原）。
--   2) 沿用评价表的既有约定：status 1-正常 0-已隐藏，**隐藏优先于删除**。
--      隐藏后立即从前台消失，但数据仍在，事后可追溯、可申诉、可恢复；
--      物理删除只留给垃圾数据清理。
--   3) 存量数据一律置 1（DEFAULT 1 自动完成），不写 UPDATE 语句 ——
--      存量书单在 V6 之后才可能出现，此刻全部是正常状态。
--   4) 索引：管理端主路径是「按状态筛选 + 创建时间倒序」，
--      单独建 (status, create_time) 而不是并进 (is_public, create_time) ——
--      后台筛选状态时不需要 is_public 参与，两列前置才能让索引真正生效。
-- =====================================================================

ALTER TABLE `book_list`
    ADD COLUMN `status` TINYINT NOT NULL DEFAULT 1
        COMMENT '状态：1-正常 0-已隐藏（平台治理用，与 is_public 语义正交）'
        AFTER `book_count`;

-- 管理端书单治理主路径：按状态筛选 + 按创建时间倒序
ALTER TABLE `book_list`
    ADD KEY `idx_book_list_status_time` (`status`, `create_time`);
